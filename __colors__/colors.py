"""
Color codes for terminal output
Provides ANSI color codes for colored terminal text
"""

# ANSI Color Codes
fc = '\033[94m'   # Foreground Cyan
fg = '\033[92m'   # Foreground Green
fr = '\033[91m'   # Foreground Red
fy = '\033[93m'   # Foreground Yellow
fb = '\033[94m'   # Foreground Blue
fm = '\033[95m'   # Foreground Magenta
sd = '\033[39m'   # Standard/Default
sb = '\033[39m'   # Standard/Default Bold

# Alternative names
CYAN = fc
GREEN = fg
RED = fr
YELLOW = fy
BLUE = fb
MAGENTA = fm
DEFAULT = sd
